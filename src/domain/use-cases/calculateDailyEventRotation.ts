/**
 * Obtiene el evento oficial correspondiente al ciclo según un hash de fecha determinista (10:00 UTC)
 */
export function getDailyEventForCycle(cycleDateUtc: string): DailyEventItem {
  let hash = 0;
  for (let i = 0; i < cycleDateUtc.length; i++) {
    hash = (hash * 31 + cycleDateUtc.charCodeAt(i)) % OFFICIAL_DAILY_EVENTS.length;
  }
  const index = Math.abs(hash) % OFFICIAL_DAILY_EVENTS.length;
  return OFFICIAL_DAILY_EVENTS[index];
}
